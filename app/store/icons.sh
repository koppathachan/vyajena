#!/usr/bin/env bash
# Regenerates the launcher icons from the one master (app-release design D11).
# macOS only: draw.swift (CoreText) draws the three source images, sips scales
# them. The outputs are committed; run this only when the icon changes.
#
#   app/store/icons.sh
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
app="$(cd "$here/.." && pwd)"
icon="$here/icon"
res="$app/android/app/src/main/res"
ios="$app/ios/Runner/Assets.xcassets/AppIcon.appiconset"

swift "$icon/draw.swift" "$icon"

scale() { # <source> <pixels> <destination>
  mkdir -p "$(dirname "$3")"
  sips -z "$2" "$2" "$1" --out "$3" >/dev/null
}

# Android: legacy square icon (API 24-25) at 48 dp, adaptive layers at 108 dp.
for pair in mdpi:1 hdpi:1.5 xhdpi:2 xxhdpi:3 xxxhdpi:4; do
  density="${pair%%:*}"
  factor="${pair##*:}"
  legacy="$(awk "BEGIN { print int(48 * $factor) }")"
  layer="$(awk "BEGIN { print int(108 * $factor) }")"
  scale "$icon/master.png" "$legacy" "$res/mipmap-$density/ic_launcher.png"
  scale "$icon/foreground.png" "$layer" "$res/mipmap-$density/ic_launcher_foreground.png"
  scale "$icon/monochrome.png" "$layer" "$res/mipmap-$density/ic_launcher_monochrome.png"
done

mkdir -p "$res/mipmap-anydpi-v26"
cat >"$res/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/store/icons.sh (app-release design D11). -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
XML
cat >"$res/values/ic_launcher_background.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/store/icons.sh: the master icon's background. -->
<resources>
    <color name="ic_launcher_background">#F1F3F5</color>
</resources>
XML

# iOS: iPhone sizes and the App Store icon, opaque (design D14: iPhone only).
for spec in 20:2 20:3 29:1 29:2 29:3 40:2 40:3 60:2 60:3 1024:1; do
  points="${spec%%:*}"
  factor="${spec##*:}"
  scale "$icon/master.png" "$((points * factor))" "$ios/Icon-App-${points}x${points}@${factor}x.png"
done

# Play store listing: the 512 px icon (the master, scaled) and the feature
# graphic (draw.swift) stay in app/store/icon for the owner to upload.
scale "$icon/master.png" 512 "$icon/play-icon-512.png"
