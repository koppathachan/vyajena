//! The bridge between the Flutter app and the device core (flutter-app design
//! D2): thin `flutter_rust_bridge` glue around [`client::Client`].
//!
//! It holds no logic. Each function in [`api`] forwards to the core, mapping
//! its types to plain ones Dart can hold and its errors to
//! [`api::error::CoreError`]. Keys never cross it; decrypted text crosses only
//! to be shown (app-ui: UI goes through the core). Its own code logs nothing.
//!
//! - [`api`]: what Dart sees. `flutter_rust_bridge_codegen generate` (run in
//!   `app/`) reads it and writes `src/frb_generated.rs` and
//!   `app/lib/src/rust/`; both are committed and never edited by hand.
//! - `map` (private): core types to bridge types.
//!
//! The generated FFI file is the one place with `unsafe` code, the isolated
//! exception `openspec/config.yaml` allows; [`api`] forbids it.

pub mod api;
// Generated by `flutter_rust_bridge_codegen generate`; rustfmt and clippy
// leave it as generated.
#[rustfmt::skip]
#[allow(clippy::all, clippy::pedantic, unreachable_pub, unused, missing_docs)]
mod frb_generated;
mod map;
