//! Regenerates the committed gRPC code for the `vyajena.v1` contract
//! (pi-server-core design D2).
//!
//! Run from anywhere in the workspace, after changing a file under `proto/`:
//!
//! ```text
//! cargo run -p pbgen
//! ```
//!
//! It writes one file per side, messages and stubs together:
//!
//! - `server/src/pb.rs`: messages plus server stubs (the Pi).
//! - `server/tests/support/pb.rs`: messages plus client stubs (the Pi's tests).
//! - `client/src/pb.rs`: messages plus client stubs (the device core,
//!   client-core design D1).
//!
//! The output is committed. CI never runs this; it only builds the committed
//! files.

#![forbid(unsafe_code)]

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

/// One generated file: where it goes and which stubs it holds.
struct Target {
    path: &'static str,
    server: bool,
    client: bool,
}

const TARGETS: &[Target] = &[
    Target {
        path: "server/src/pb.rs",
        server: true,
        client: false,
    },
    Target {
        path: "server/tests/support/pb.rs",
        server: false,
        client: true,
    },
    Target {
        path: "client/src/pb.rs",
        server: false,
        client: true,
    },
];

/// The protobuf package; prost names its output file after it.
const PACKAGE: &str = "vyajena.v1";

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("pbgen has no parent directory")?
        .to_path_buf();
    let proto_root = root.join("proto");

    let mut files = Vec::new();
    collect_protos(&proto_root, &mut files)?;
    files.sort();
    if files.is_empty() {
        bail!("no .proto files under {}", proto_root.display());
    }
    let fds = protox::compile(&files, [&proto_root]).context("parsing the .proto files")?;

    for target in TARGETS {
        let scratch = tempdir(&root, target.path)?;
        tonic_prost_build::configure()
            .build_server(target.server)
            .build_client(target.client)
            // Callers build their own channel (pinned TLS), so no `connect()`.
            .build_transport(false)
            .emit_rerun_if_changed(false)
            .out_dir(&scratch)
            .compile_fds(fds.clone())
            .with_context(|| format!("generating {}", target.path))?;

        let generated = scratch.join(format!("{PACKAGE}.rs"));
        let body = fs::read_to_string(&generated)
            .with_context(|| format!("reading {}", generated.display()))?;
        fs::remove_dir_all(&scratch).ok();

        let out = root.join(target.path);
        if let Some(dir) = out.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&out, format!("{}{body}", header(target)))
            .with_context(|| format!("writing {}", out.display()))?;
        println!("wrote {}", target.path);
    }
    Ok(())
}

fn header(target: &Target) -> String {
    let side = if target.server {
        "messages and server stubs"
    } else {
        "messages and client stubs"
    };
    format!(
        "// @generated by `cargo run -p pbgen` from proto/vyajena/v1 ({side}).\n\
         // Do not edit: change the .proto files and regenerate (pi-server-core D2).\n\
         #![allow(clippy::all, clippy::pedantic, missing_docs)]\n\n"
    )
}

/// A fresh scratch directory under `target/`, so nothing lands in the tree.
fn tempdir(root: &Path, name: &str) -> Result<PathBuf> {
    let dir = root
        .join("target")
        .join("pbgen")
        .join(name.replace('/', "_"));
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    fs::create_dir_all(&dir)?;
    Ok(dir)
}

fn collect_protos(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    for entry in fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))? {
        let path = entry?.path();
        if path.is_dir() {
            collect_protos(&path, out)?;
        } else if path.extension().is_some_and(|ext| ext == "proto") {
            out.push(path);
        }
    }
    Ok(())
}
