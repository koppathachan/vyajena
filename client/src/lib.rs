//! The vyajena2 device core: OpenMLS, keys, the local store and the connection
//! to the server, behind one async API and one ordered event stream.
//!
//! **The API for UIs** (the terminal client now, Flutter through
//! `flutter_rust_bridge` later) is [`Client`] and the [`Event`]s it emits. Its
//! types are plain Rust structs and enums: no OpenMLS or protobuf type appears
//! in them (client-core design D2).
//!
//! One folder per feature (design D1). The feature modules are public so the
//! tests in `tests/` can reach them through the public API, as the server's
//! tests do; UIs use [`Client`] only.
//!
//! - [`keystore`]: where keys live (OS keychain, opt-in 0600 file, memory).
//! - [`store`]: the local SQLite database (messages, pinned identity keys,
//!   encrypted OpenMLS state).
//! - [`mls`]: OpenMLS: the encrypted storage provider, the group's
//!   configuration and the checks OpenMLS does not do.
//! - [`identity`]: identity, device auth and MLS keys, certificates, invite
//!   and link payloads.
//! - [`net`]: pinned TLS, the gRPC channel, challenge authentication.
//! - [`membership`]: building commits (admin actions, re-add, server Removes,
//!   rotation) and checking fetched KeyPackages.
//! - [`keys`]: KeyPackages, the last-resort refresh, rotation timing.
//! - `engine` (private): the one task that owns the connection, the
//!   `Connect` stream and the group, and runs everything in order.
//! - [`messaging`]: filled in by task group 6.

