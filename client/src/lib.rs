//! The vyajena2 device core: OpenMLS, keys, the local store and the connection
//! to the Pi, behind one async API and one ordered event stream.
//!
//! **The API for UIs** (the terminal client now, Flutter through
//! `flutter_rust_bridge` later) is [`Client`] and the [`Event`]s it emits. Its
//! types are plain Rust structs and enums: no OpenMLS or protobuf type appears
//! in them (client-core design D2).
//!
//! One folder per feature (design D1). The feature modules are public so the
//! tests in `tests/` can reach them through the public API, as the server's
//! tests do; UIs use [`Client`] only.
//!
//! - [`keystore`]: where keys live (OS keychain, opt-in 0600 file, memory).
//! - [`store`]: the local SQLite database (messages, pinned identity keys,
//!   encrypted OpenMLS state).
//! - [`mls`]: OpenMLS: the encrypted storage provider and, later, the group.
//! - [`identity`], [`net`], [`membership`], [`keys`], [`messaging`]: filled in
//!   by later task groups of the `client-core` change.

#![forbid(unsafe_code)]

mod client;
pub mod clock;
mod events;
pub mod identity;
pub mod keys;
pub mod keystore;
pub mod membership;
pub mod messaging;
pub mod mls;
pub mod net;
// Generated by `cargo run -p pbgen`; rustfmt leaves it as generated. Used by
// later task groups (networking, messaging); never part of the public API.
#[rustfmt::skip]
#[allow(dead_code, unreachable_pub)]
mod pb;
pub mod store;

pub use client::{Client, ClientConfig, ClientError};
pub use clock::{Clock, ManualClock, SystemClock};
pub use events::{
    ConnectionState, DeviceId, Event, EventStream, Message, MessageBody, MessageId, SendStatus,
    UserId,
};
